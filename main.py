# ---------------- RESULT DISPLAY ----------------

def display_result(result):

    if "error" in result:
        st.error(result["error"])
        return

    score = result["score"]
    level = result["level"]
    label = result["label"]

    colors = {
        "low": "green",
        "medium": "orange",
        "high": "red",
        "critical": "red"
    }

    st.markdown("## 🔍 Scan Results")

    col1, col2 = st.columns(2)

    with col1:
        st.metric("Risk Score", f"{score}/100")
        st.progress(score / 100)

    with col2:
        st.markdown(
            f"### :{colors[level]}[{label}]"
        )
        st.write(f"Risk Level: **{level.upper()}**")

    st.markdown("### 💡 Recommendation")
    st.info(result["advice"])

    if result.get("kind") == "email":
        st.write("**Sender:**", result["sender"])
        st.write("**Domain:**", result["domain"])

        st.markdown("### 🔗 Links Found")

        if result["links"]:
            for url, sc, lb, lv in result["links"]:
                st.write(f"**{url}**")
                st.write(f"Risk: {sc}/100 — {lb}")
                st.divider()
        else:
            st.success("No links detected.")

    else:
        st.write("**Domain:**", result["domain"])
        st.write("**Protocol:**", result["scheme"])
        st.write("**Scanned URL:**")
        st.code(result["url"])

    st.markdown("### ⚠️ Detailed Findings")

    if result["findings"]:
        for sev, title, detail, points in result["findings"]:

            if sev == "good":
                st.success(f"✅ {title}: {detail}")

            elif sev == "low":
                st.info(f"ℹ️ {title}: {detail}")

            elif sev == "medium":
                st.warning(f"⚠️ {title}: {detail}")

            else:
                st.error(f"🚨 {title}: {detail}")

            if points:
                st.caption(f"Risk points: +{points}")

    else:
        st.success("No suspicious patterns found.")


